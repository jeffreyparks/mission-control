"""
Learned preferences: what your own decisions say you want, as a reviewable draft.

The fit judge reads me/profile.md and your resume - what you SAY you want. This
reads what you DO: the roles you closed with a reason that is about the role
itself (store.PREFERENCE_CLOSE_REASONS), and the roles you pursued (researching,
applied, or heard back from an employer). It never learns from a close without
a reason, or from a neutral one ("Chose another role at org", "Posting closed"):
those say nothing about what you want.

Two halves, deliberately split:
  - Python computes the evidence: per industry, function, level and category,
    how often you passed vs pursued against your overall rate, and where the
    model's recommendation and your decision disagreed. Only groups with at
    least MIN_DECISIONS decisions and a clear lean become candidates.
  - One LLM call reads the candidates with a few of your notes, drops the ones
    that are confounded or already covered by another, and phrases the rest as
    guidance for the fit judge. The counts in the output are attached here, from
    the evidence, never taken from the model.

The result is a DRAFT (me/learned.draft.md). Nothing reaches the fit prompt
until you approve it into me/learned.md - with --approve, or by editing and
saving it yourself. me/learned.md is yours: this module never overwrites it
except through --approve, which keeps the previous copy as learned.prev.md.

    uv run agents/preferences.py              # write a fresh draft
    uv run agents/preferences.py --evidence   # print the evidence, no LLM call
    uv run agents/preferences.py --approve    # promote the draft
"""
import argparse
import json
import re
import shutil
import sys
from datetime import datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from llm import LLM, LLMError, output_budget           # noqa: E402
from store import PREFERENCE_CLOSE_REASONS, Store      # noqa: E402

DRAFT = "me/learned.draft.md"
LEARNED = "me/learned.md"
PREVIOUS = "me/learned.prev.md"

# Only decisions made inside this window count; tastes move.
WINDOW_DAYS = 180

# A group needs this many decisions before it can say anything at all.
MIN_DECISIONS = 5
# ...and this many on the side it leans toward.
MIN_LEANING = 4
# Pursue rates are shrunk toward your overall rate by this many pseudo-decisions,
# so five decisions cannot look like certainty.
PRIOR_STRENGTH = 4
# How far a group's shrunk pursue rate must sit from your overall rate to lean.
AVOID_RATIO = 0.6
SEEK_RATIO = 1.5
# A leaning group becomes a candidate only when you overrode the model on at
# least this many of its roles, AND on at least this share of the decisions on
# the side it leans to. A pattern the model already follows (you closed what it
# said to skip) teaches it nothing and only lengthens the prompt - and in a big
# group, a couple of overrides among ninety agreements is still agreement.
MIN_DISAGREEMENTS = 2
MIN_DISAGREEMENT_SHARE = 0.2

# A draft is regenerated by the daily run once the last one is this old.
DRAFT_INTERVAL_DAYS = 7

NOTES_PER_CANDIDATE = 5
# Output budget per candidate verdict: id, keep, and a one-sentence statement or
# a short why_dropped. The 4096 default cut the answer off at 19 candidates (over
# 200 tokens each), so this allows about twice that.
VERDICT_TOKENS_PER_CANDIDATE = 400
VERDICT_TOKENS_OVERHEAD = 500

PURSUED_STATUSES = {"02 Researching", "03 Applied"}

# An employer outcome on a role means you applied to it.
_NOT_AN_APPLICATION = {"", "closed"}

# Title level, most senior first; the first pattern that matches wins.
_LEVELS = [
    ("VP and above", re.compile(r"\b(vp|vice president|chief|head of|svp|evp|cxo|c[dt]o)\b", re.I)),
    ("Director", re.compile(r"\bdirector\b", re.I)),
    ("Principal / Staff / Lead", re.compile(r"\b(principal|staff|lead)\b", re.I)),
    ("Manager", re.compile(r"\bmanager\b", re.I)),
    ("Junior", re.compile(r"\b(associate|junior|jr\.?|intern|internship|ii|analyst)\b", re.I)),
    ("Senior IC", re.compile(r"\b(senior|sr\.?)\b", re.I)),
]


def title_level(title):
    for label, pattern in _LEVELS:
        if pattern.search(title or ""):
            return label
    return UNSPECIFIED_LEVEL


UNSPECIFIED_LEVEL = "Unspecified level"


def industry(sector):
    """"Finance - Banking" -> "Finance". Unknown and blank are not an industry."""
    head = (sector or "").split(" - ")[0].strip()
    return head if head and head.lower() != "unknown" else None


