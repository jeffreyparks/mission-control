def _prompt(evidence, profile_text):
    return f"""You maintain a short "learned preferences" note that a job-fit judge reads
next to the candidate's stated profile. It is built ONLY from what the candidate
actually did: roles they passed on for a stated reason, and roles they pursued.

THE CANDIDATE'S STATED PROFILE (for context - do not restate it):
{profile_text[:3000]}

OVERALL: {evidence['decisions']} decisions, {evidence['pursued']} pursued, \
{evidence['passed']} passed. Base pursue rate {evidence['base_pursue_rate']}.

CANDIDATE PATTERNS (each clears a minimum-evidence bar, and in each the candidate
overrode the model's recommendation at the time more than once - these are the
corrections the judge needs):
{json.dumps(evidence['candidates'], indent=2)}

For each candidate decide keep or drop, then write one statement for each kept one.

RULES:
  - Drop a candidate that another candidate explains better. If "Data Science & ML
    at Finance" and "Finance" both lean avoid, and the notes cite industry, keep the
    industry one and drop the narrower one - or the reverse if the evidence says so.
    Never keep two statements that say the same thing.
  - Drop a candidate whose lean is plausibly a side effect of something else
    (a level or location problem showing up as an industry pattern). Say why.
  - Drop a candidate that the stated profile already says plainly; the judge has
    that. Keep one that sharpens or contradicts the profile - those matter most.
  - A statement is ONE sentence of guidance to the fit judge, concrete, in the
    candidate's terms: "Treat roles at banks, insurers and asset managers as a
    weak fit whatever the function - the candidate passes on them for industry
    reasons." No counts or percentages - those are attached separately.
  - Use the sample notes to name WHY when they say so. Do not invent a reason.
  - Keeping nothing is a correct answer when nothing is clear.

Return ONLY a JSON array, one object per candidate id:
[{{"id": "<candidate id>", "keep": true | false,
   "statement": "<one sentence, when kept>", "why_dropped": "<short clause, when dropped>"}}]"""


def make_validator(evidence):
    ids = {c["id"] for c in evidence["candidates"]}

    def validate(data):
        if not isinstance(data, list) or not data:
            return False
        for item in data:
            if not isinstance(item, dict) or item.get("id") not in ids:
                return False
            if not isinstance(item.get("keep"), bool):
                return False
            if item["keep"] and not (isinstance(item.get("statement"), str)
                                     and item["statement"].strip()):
                return False
        return True

    return validate


def _evidence_line(c):
    reasons = ", ".join(f"{k.lower()} {v}" for k, v in c["pass_reasons"].items())
    line = (f"{c['dimension']} = {c['value']}: passed {c['passed']}, "
            f"pursued {c['pursued']} of {c['decisions']}")
    if reasons:
        line += f" (passed for: {reasons})"
    if c["passed_though_model_liked"]:
        line += f"; passed on {c['passed_though_model_liked']} the model rated apply/research"
    if c["pursued_though_model_skipped"]:
        line += f"; pursued {c['pursued_though_model_skipped']} the model said to skip"
    return line


def render_draft(evidence, verdicts, now=None):
    now = now or datetime.now()
    by_id = {c["id"]: c for c in evidence["candidates"]}
    kept = [(by_id[v["id"]], v) for v in verdicts if v.get("keep") and v["id"] in by_id]
    dropped = [(by_id[v["id"]], v) for v in verdicts if not v.get("keep") and v["id"] in by_id]

    lines = [
        "# Learned preferences",
        "",
        f"<!-- DRAFT generated {now:%Y-%m-%d} from {evidence['decisions']} decisions in the last",
        f"     {WINDOW_DAYS} days ({evidence['pursued']} pursued, {evidence['passed']} passed for a reason",
        "     about the role). Nothing here is used until it is saved as me/learned.md:",
        "         uv run agents/preferences.py --approve",
        "     Edit freely first - delete a line you disagree with, reword one that is off.",
        "     The fit judge reads the bullet text; these comments are stripped. -->",
        "",
    ]
    for lean, heading in (("avoid", "Weigh down"), ("seek", "Weigh up")):
        items = [(c, v) for c, v in kept if c["lean"] == lean]
        if not items:
            continue
        lines += [f"## {heading}", ""]
        for c, v in items:
            lines.append(f"- {v['statement'].strip()}")
            lines.append(f"  <!-- evidence: {_evidence_line(c)} -->")
        lines.append("")
    if not kept:
        lines += ["_No clear pattern in your decisions yet._", ""]
    if evidence.get("agreed"):
        lines.append("<!-- real patterns the model already follows, so left out:")
        for c in evidence["agreed"]:
            lines.append(f"     - {c['dimension']} = {c['value']} ({c['lean']}): "
                         f"passed {c['passed']}, pursued {c['pursued']} of {c['decisions']}")
        lines.append("-->")
    if dropped:
        lines.append("<!-- considered and dropped:")
        for c, v in dropped:
            lines.append(f"     - {c['dimension']} = {c['value']} ({c['lean']}): "
                         f"{(v.get('why_dropped') or 'no reason given').strip()}")
        lines.append("-->")
    return "\n".join(lines).rstrip() + "\n"


def write_draft(base_dir, llm=None, now=None):
    """Build the evidence, ask for a verdict on each candidate, write the draft.
    Returns the draft path, or None when there is nothing to write."""
    base_dir = Path(base_dir)
    evidence = build_evidence(load_decisions(Store(base_dir), now=now))
    print(f"  preferences: {evidence['decisions']} decision(s), "
          f"{len(evidence['candidates'])} candidate pattern(s), "
          f"{len(evidence['agreed'])} the model already follows")
    if not evidence["candidates"]:
        verdicts = []
    else:
        profile = base_dir / "me/profile.md"
        llm = llm or LLM(base_dir)
        try:
            verdicts = llm.complete_json(
                _prompt(evidence, profile.read_text() if profile.exists() else ""),
                tag="preferences", validate=make_validator(evidence),
                max_tokens=output_budget(len(evidence["candidates"]),
                                         per_item=VERDICT_TOKENS_PER_CANDIDATE,
                                         overhead=VERDICT_TOKENS_OVERHEAD))
        except LLMError as exc:
            print(f"  ! preferences draft failed, previous draft kept: {exc}")
            return None
    path = base_dir / DRAFT
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_draft(evidence, verdicts, now=now))
    print(f"  preferences draft -> {path.relative_to(base_dir)}")
    return path


def draft_is_due(base_dir, now=None):
    path = Path(base_dir) / DRAFT
    if not path.exists():
        return True, "no draft yet"
    age = ((now or datetime.now()) - datetime.fromtimestamp(path.stat().st_mtime)).days
    if age >= DRAFT_INTERVAL_DAYS:
        return True, f"{age}d since last draft"
    return False, f"{DRAFT_INTERVAL_DAYS - age}d until next draft"


def approve(base_dir):
    """Promote the draft to me/learned.md, keeping the previous copy."""
    base_dir = Path(base_dir)
    draft, learned = base_dir / DRAFT, base_dir / LEARNED
    if not draft.exists():
        raise FileNotFoundError(f"no draft at {DRAFT} - run preferences.py first")
    if learned.exists():
        shutil.copy2(learned, base_dir / PREVIOUS)
    shutil.copy2(draft, learned)
    return learned


def main(argv=None):
    import workspace
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    workspace.add_argument(ap)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--evidence", action="store_true",
                      help="print the evidence and candidate patterns, no LLM call")
    mode.add_argument("--approve", action="store_true",
                      help=f"promote {DRAFT} to {LEARNED}")
    args = ap.parse_args(argv)
    base = workspace.resolve(args.user)

    if args.approve:
        print(f"approved -> {approve(base).relative_to(base)}")
        return 0
    if args.evidence:
        print(json.dumps(build_evidence(load_decisions(Store(base))), indent=2))
        return 0
    return 0 if write_draft(base) else 1


if __name__ == "__main__":
    sys.exit(main())
