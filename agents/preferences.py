def decision_of(row):
    """"passed", "pursued", or None when the row says nothing about you."""
    if row["status"] in PURSUED_STATUSES:
        return "pursued"
    if (row["outcomes"] or "").strip().lower() not in _NOT_AN_APPLICATION:
        return "pursued"
    if row["status"] == "04 Closed" and row["close_reason"] in PREFERENCE_CLOSE_REASONS:
        return "passed"
    return None


def recommendation_at(history, when, current):
    """What the model recommended at `when`, from the role's logged
    recommendation changes [(ts, old, new), ...] in time order.

    The first change AFTER the decision still carries, as its old value, what
    the model was saying when you decided. With no later change, the current
    value has held since before the decision."""
    for ts, old, _new in history:
        if when and ts > when:
            return old
    return current


def load_decisions(store, now=None, window_days=WINDOW_DAYS):
    """Every role you made a preference-bearing decision on, inside the window.

    A decision is dated by the last time YOU changed its status; failing that,
    the last time you touched its close reason or outcome; failing that, the
    row's own last update.

    Each decision carries the model's recommendation AT THAT TIME, not today's.
    Today's is shaped by the learned preferences themselves - once a pattern is
    learned the model agrees with you, and judging agreement against that would
    make every learned pattern erase itself on the next draft."""
    now = now or datetime.now()
    cutoff = (now - timedelta(days=window_days)).isoformat(timespec="seconds")
    with store.connect() as conn:
        status_ts = {r["role_id"]: r["ts"] for r in conn.execute(
            "SELECT role_id, MAX(ts) ts FROM changes WHERE field='status' "
            "AND actor NOT IN ('pipeline','migration') GROUP BY role_id")}
        touched = {r["role_id"]: r["ts"] for r in conn.execute(
            "SELECT role_id, MAX(ts) ts FROM changes "
            "WHERE field IN ('status','close_reason','outcomes') AND actor != 'pipeline' "
            "GROUP BY role_id")}
        rec_history = {}
        for r in conn.execute("SELECT role_id, ts, old_value, new_value FROM changes "
                              "WHERE field='recommendation' ORDER BY ts, seq"):
            rec_history.setdefault(r["role_id"], []).append((r["ts"], r["old_value"], r["new_value"]))
        rows = [dict(r) for r in conn.execute("SELECT * FROM roles")]

    decisions = []
    for row in rows:
        kind = decision_of(row)
        if not kind:
            continue
        when = status_ts.get(row["id"]) or touched.get(row["id"]) or row.get("updated_at") or ""
        if when and when < cutoff:
            continue
        decisions.append({
            "id": row["id"], "org": row["org"], "title": row["title"],
            "decision": kind, "reason": row["close_reason"] if kind == "passed" else None,
            "notes": (row["notes"] or "").strip(),
            "decided_at": when,
            "recommendation": recommendation_at(rec_history.get(row["id"], []), when,
                                                row["recommendation"]),
            "fit_score": row["fit_score"],
            "industry": industry(row["sector"]),
            "function": row["role_function"],
            "level": title_level(row["title"]),
            "category": row["role_cat"],
        })
    return decisions


DIMENSIONS = [("industry", "Employer industry"), ("function", "Function"),
              ("level", "Title level"), ("category", "Your role category")]


def _group_stats(items, base_rate):
    passed = [d for d in items if d["decision"] == "passed"]
    pursued = [d for d in items if d["decision"] == "pursued"]
    n = len(items)
    shrunk = (len(pursued) + PRIOR_STRENGTH * base_rate) / (n + PRIOR_STRENGTH)
    reasons = {}
    for d in passed:
        reasons[d["reason"]] = reasons.get(d["reason"], 0) + 1
    return {
        "decisions": n, "passed": len(passed), "pursued": len(pursued),
        "pursue_rate": round(len(pursued) / n, 2) if n else None,
        "shrunk_rate": round(shrunk, 2),
        "pass_reasons": dict(sorted(reasons.items(), key=lambda kv: -kv[1])),
        # Where you and the model disagreed - what the fit judge most needs to hear.
        "passed_though_model_liked": sum(
            1 for d in passed if d["recommendation"] in ("apply", "research")),
        "pursued_though_model_skipped": sum(
            1 for d in pursued if d["recommendation"] == "skip"),
    }


def _lean(stats, base_rate):
    if stats["decisions"] < MIN_DECISIONS:
        return None
    if stats["passed"] >= MIN_LEANING and stats["shrunk_rate"] <= base_rate * AVOID_RATIO:
        return "avoid"
    if stats["pursued"] >= MIN_LEANING and stats["shrunk_rate"] >= min(0.95, base_rate * SEEK_RATIO):
        return "seek"
    return None


def build_evidence(decisions):
    """Baseline plus the candidate patterns - groups with enough decisions and
    a clear lean away from your overall pursue rate."""
    n = len(decisions)
    pursued = sum(1 for d in decisions if d["decision"] == "pursued")
    base_rate = pursued / n if n else 0.0
    evidence = {"decisions": n, "passed": n - pursued, "pursued": pursued,
                "base_pursue_rate": round(base_rate, 2), "candidates": [], "agreed": []}
    if not n:
        return evidence

    groups = {}
    for d in decisions:
        for dim, _label in DIMENSIONS:
            # "No level word in the title" is the matcher's leftover, not a group.
            if d.get(dim) and d[dim] != UNSPECIFIED_LEVEL:
                groups.setdefault((dim, d[dim]), []).append(d)
        # One cross: industry x function is where "passes on banks" and
        # "passes on finance work" come apart.
        if d.get("industry") and d.get("function"):
            groups.setdefault(("industry x function", f"{d['function']} at {d['industry']}"),
                              []).append(d)

    for (dim, value), items in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        stats = _group_stats(items, base_rate)
        lean = _lean(stats, base_rate)
        if not lean:
            continue
        overrides = (stats["passed_though_model_liked"] if lean == "avoid"
                     else stats["pursued_though_model_skipped"])
        leaning = stats["passed"] if lean == "avoid" else stats["pursued"]
        if overrides < MIN_DISAGREEMENTS or overrides < MIN_DISAGREEMENT_SHARE * leaning:
            # Real pattern, but the model was already making the same call.
            evidence["agreed"].append({"dimension": dim, "value": value, "lean": lean, **stats})
            continue
        side = "passed" if lean == "avoid" else "pursued"
        notes = [f"{d['title']} @ {d['org']}: {d['notes'][:160]}"
                 for d in items if d["decision"] == side and d["notes"]][:NOTES_PER_CANDIDATE]
        evidence["candidates"].append({
            "id": f"c{len(evidence['candidates']) + 1}", "dimension": dim, "value": value,
            "lean": lean, **stats, "sample_notes": notes,
        })
    return evidence


